def triangular_certificate(mode, matrix):
    target={'b2':b2,'c3':c3,'c2':c2}[mode]
    raw=[list(row) for row in matrix]
    if mode=='c3':raw=raw[:12]+[[27*a+4*b for a,b in zip(raw[12],raw[13])]]
    triangles=[];combinations=[]
    for z,(row,j) in enumerate(zip(raw,PIVOTS[mode])):
        row=list(row);factors=[]
        for prev,piv in zip(triangles,PIVOTS[mode][:z]):
            factor=S.cancel(row[piv]/prev[piv]);factors.append(factor)
            row=[S.cancel(a-factor*b) for a,b in zip(row,prev)]
        assert row[j]!=0
        den=S.lcm([S.denom(v) for v in row+factors])
        row=[S.expand(den*v) for v in row]
        pc=S.Poly(row[j],target)
        assert len(pc.terms())==1, (mode,z,row[j])
        scale=den/pc.terms()[0][1]
        row=[S.cancel(v/pc.terms()[0][1]) for v in row]
        assert all(S.denom(v).is_number for v in row)
        coefficients=[S.cancel(scale)]+[S.cancel(-scale*f) for f in factors]
        assert all(S.denom(v).is_number for v in coefficients)
        triangles.append(row);combinations.append(coefficients)
    return triangles,combinations

def generate_elimination(matrices):
    for mode,matrix in matrices.items():
        tri,comb=triangular_certificate(mode,matrix)
        target={'b2':b2,'c3':c3,'c2':c2}[mode]
        hypotheses='(hb : t.b₃ = 0) (h4 : t.c₄ = 0) (h5 : t.c₅ = 0)'
        args='t hb h4 h5'
        if mode in ('c3','c2'):hypotheses+=' (hb2 : t.b₂ = 0)';args+=' hb2'
        if mode=='c2':hypotheses+=' (hc3 : t.c₃ = 0)';args+=' hc3'
        s=f"""import SexticC3.CubeLeadingSevenRows{mode.upper()}

/-! Generated exact triangular elimination. Every polynomial identity is
replayed by Lean, and each pivot is a power of the stated nonzero parameter. -/
noncomputable section
set_option linter.unusedSectionVars false
namespace SexticC3.CubeLeading.Polynomial
open MvPolynomial
variable {{K : Type*}} [Field K] [CharZero K]

set_option maxHeartbeats 4000000 in
lemma seven_{mode}_coordinates_zero (t : HamiltonianParameters K)
    {hypotheses} (ht : {lean(target)} ≠ 0) (x : Fin 13 → K)
    (hf : ∀ n : ℕ, Static t.toGateParameters ((bracket (hamiltonian t))^[n] (sevenCombination t x))) :
    x = 0 := by
"""
        for r,label in enumerate(ROWS[mode]):s+=f'  have e{r} := seven_{mode}_row_{r} {args} x (hf {label[0]})\n'
        for z,(row,cs) in enumerate(zip(tri,comb)):
            rawname=f'e{z}' if mode!='c3' or z!=12 else '(27*e12+4*e13)'
            parts=[f'{lean(cs[0])} * {rawname}']+[f'{lean(c)} * z{r}' for r,c in enumerate(cs[1:]) if c]
            s+=f'  have z{z} : {dot(row)} = 0 := by\n    linear_combination '+ ' + '.join(parts)+'\n'
        zeros=[]
        for z in reversed(range(13)):
            j=PIVOTS[mode][z];pv=tri[z][j]
            exponent=S.Poly(pv,target).degree()
            s+=f'  have v{j} : x {j} = 0 := by\n'
            s+=f'    have hp : {lean(pv)} * x {j} = 0 := by\n'
            s+=f'      simpa only ['+', '.join(f'v{k}' for k in zeros)+(', ' if zeros else '')+f'mul_zero, add_zero, zero_add] using z{z}\n'
            if exponent==0:s+='    simpa using hp\n'
            else:s+=f'    exact (mul_eq_zero.mp hp).resolve_left '+('ht' if exponent==1 else f'(pow_ne_zero {exponent} ht)')+'\n'
            zeros.append(j)
        s+='  funext k\n  fin_cases k\n'
        for k in range(13):s+=f'  · exact v{k}\n'
        s+='\nend SexticC3.CubeLeading.Polynomial\n'
        (ROOT/f'SexticC3/CubeLeadingSevenEliminate{mode.upper()}.lean').write_text(s)
        print(mode,'rows',len(matrix),'triangular terms',sum(len(S.Add.make_args(v)) for row in tri for v in row if v))

