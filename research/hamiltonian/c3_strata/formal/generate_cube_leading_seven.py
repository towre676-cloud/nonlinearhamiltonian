"""Generate exact seven-parameter coefficient witnesses and Lean proof statements.

Every generated statement is checked by Lean; SymPy is not part of the trusted
proof chain. All parameter polynomials are kept in the unnormalized variables.
"""
from pathlib import Path
from math import lcm
import sympy as S

ROOT = Path(__file__).resolve().parent
q, P = S.symbols('q P')
b0, b1, b2, c1, c2, c3 = S.symbols('b0 b1 b2 c1 c2 c3')
PARAMS = (b0, b1, b2, c1, c2, c3)
FREE = [(i, j) for j in range(4) for i in range(3)] + [(0, j) for j in range(4, 7)]
KEEP = [r for r, ij in enumerate(FREE) if ij not in ((0, 0), (0, 3))]

def basis_data():
    x = S.symbols('x0:15')
    E = b1 + c3 + 2*b2*q
    a = {j: x[FREE.index((0, j))] for j in range(4, 7)}
    for j in range(3, -1, -1):
        get = lambda r: a.get(r, S.Integer(0))
        rhs = (-6*(j+1)**2*S.diff(get(j+1),q)
               -b2*(j+1)*(j+2)*S.diff(get(j+2),q)
               +E*(j+1)*(j+2)*(j+3)*get(j+3))
        a[j] = S.expand(S.integrate(S.integrate(S.integrate(rhs,q),q),q)
                        +sum(x[FREE.index((i,j))]*q**i for i in range(3)))
    g = S.expand(sum(a[j]*P**j for j in range(7)))
    raw = [g.coeff(x[r]) for r in KEEP]
    scales = [lcm(*(int(v.q) for v in S.Poly(g,q,P,*PARAMS).coeffs())) for g in raw]
    return [S.expand(d*g) for d,g in zip(scales,raw)], scales

NAMES = dict(zip(PARAMS, ('t.b₀','t.b₁','t.b₂','t.c₁','t.c₂','t.c₃')))
def lean(e):
    e=S.sympify(e)
    if e in NAMES:return NAMES[e]
    if e.is_Integer:return str(e) if e>=0 else '('+str(e)+')'
    if e.is_Rational:return '('+str(e.p)+' / '+str(e.q)+')'
    if e.is_Add:return '('+' + '.join(lean(v) for v in e.args)+')'
    if e.is_Mul:return '('+' * '.join(lean(v) for v in e.args)+')'
    if e.is_Pow:return '('+lean(e.base)+' ^ '+str(e.exp)+')'
    raise ValueError(e)

def lean_poly(g):
    if not g:return '0'
    return ' +\n    '.join(f'monomial (exponent {i} {j}) {lean(c)}' for (i,j),c in S.Poly(g,q,P).terms())

