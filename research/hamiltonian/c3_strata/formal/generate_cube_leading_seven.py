def evaluation_data():
    basis,_=basis_data()
    B=b0+b1*q+b2*q**2;C=c1*q+c2*q**2+c3*q**3
    D=lambda g:S.expand((S.diff(B,q)*P+S.diff(C,q))*S.diff(g,P)-(3*P**2+B)*S.diff(g,q))
    polys=[[S.Poly(g,q,P) for g in basis]]
    for d in range(3):polys.append([S.Poly(D(g.as_expr()),q,P) for g in polys[-1]])
    return polys

def needed_evaluations(mode):
    needed=set()
    def add(d,i,j):
        key=(d,i,j)
        if key in needed:return
        needed.add(key)
        if d==0:return
        ns={(i,j+1),(i+1,j)}
        if j>0 or i>0:ns.add((i,j))
        if i>0:ns.add((i-1,j+1))
        if i>=2 and mode!='c2':ns.add((i-2,j+1))
        if j>=2:ns.add((i+1,j-2))
        if mode=='b2' and i>0 and (j>0 or i>=2):ns.add((i-1,j))
        for r,v in ns:add(d-1,r,v)
    for d,gate,i,j in ROWS[mode]:
        ns={(i+1,j+4)} if gate=='5' else {(i+3,j),(i+1,j+1),(i,j+3)}
        if gate=='3' and mode=='b2':
            ns.add((i+1,j+2))
            if i>0:ns.add((i-1,j+3))
        for r,v in ns:add(d,r,v)
    return sorted(needed)

