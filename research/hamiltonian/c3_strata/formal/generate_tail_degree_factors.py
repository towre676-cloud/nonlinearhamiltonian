#!/usr/bin/env python3
"""Extract the integer degree factors queried by the static-tail checker."""

from functools import reduce
import hashlib
import json
from math import gcd, lcm
from pathlib import Path
import sys
from unittest.mock import patch

FORMAL = Path(__file__).resolve().parent
INPUTS = FORMAL.parents[1] / "c3_uniform" / "inputs"
sys.path.insert(0, str(INPUTS))
import check_binary_static as checker


def degree_factors(certificate):
    """Return primitive integer coefficients, with positive leading sign."""
    factors = set()
    check_nonzero = checker.nonzero_from

    def record(poly, threshold):
        coefficients = checker.uni(poly)
        degree = max(coefficients)
        denominator = lcm(*(c.denominator for c in coefficients.values()))
        integers = [int(denominator * coefficients.get(i, 0)) for i in range(degree + 1)]
        divisor = reduce(gcd, integers)
        sign = 1 if integers[-1] > 0 else -1
        factors.add(tuple(sign * c // divisor for c in integers))
        return check_nonzero(poly, threshold)

    with patch.object(checker, "nonzero_from", record):
        checker.check(certificate)
    return sorted(factors, key=lambda row: (len(row), row))


def main():
    source = (INPUTS / "binary_static_d6.json").read_bytes()
    certificate = json.loads(source)
    if certificate["N0"] != 17 or certificate["degree"] != 6:
        raise ValueError("expected the sextic certificate at threshold seventeen")
    print("import SexticC3.TailDegreeFactors")
    print()
    print("-- Generated by generate_tail_degree_factors.py.")
    print(f"-- binary_static_d6.json SHA-256: {hashlib.sha256(source).hexdigest()}")
    print("namespace SexticC3.TailDegreeFactors")
    print()
    print("set_option maxHeartbeats 3000000 in")
    print("set_option maxRecDepth 4096 in")
    print("/-- Primitive degree polynomials queried by the sextic replay. -/")
    print("def factors : List (List ℤ) := [")
    rows = [str(list(row)) for row in degree_factors(certificate)]
    print(",\n".join("  " + row for row in rows))
    print("]")
    print()
    print("set_option maxRecDepth 4096 in")
    print("set_option maxHeartbeats 0 in")
    print("theorem factors_positive :")
    print("    factors.all (fun cs => positiveCoefficients (shift cs)) = true := by decide +kernel")
    print()
    print("theorem factors_nonzero {K : Type*} [Field K] [CharZero K]")
    print("    {cs : List ℤ} (hc : cs ∈ factors) (n : ℕ) (hn : 17 ≤ n) :")
    print("    eval (n : K) cs ≠ 0 :=")
    print("  eval_ne_zero cs (List.all_eq_true.mp factors_positive cs hc) n hn")
    print()
    print("end SexticC3.TailDegreeFactors")


if __name__ == "__main__":
    main()
