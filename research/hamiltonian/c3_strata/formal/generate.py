"""Transcribe the v1 records for degrees one through sixteen and emit Lean proof obligations.

The independent Python verifier supplies row simplification hints only.
Lean proves each row hint from Model.rowTerms and checks the recorded identities.
"""
import hashlib
import json
from math import comb, prod
from fractions import Fraction
from pathlib import Path
import sys

import sympy as s

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import verify_squarefree as source

EXPECTED = "2faae6b7a3e9d1202fb6e9f9d6f645a37a6f18e865c42a0bb5aa2f065a12462a"
VARS = source.VARIABLES


def scalar(value):
    r = Fraction(str(value))
    return f"({r.numerator})" if r.denominator == 1 else f"({r.numerator} / {r.denominator})"


def poly(terms):
    return " + ".join(
        " * ".join([scalar(c)] + [
            v if e == 1 else f"{v}^{e}" for v, e in zip("abcd", exps) if e
        ]) for exps, c in terms
    ) or "0"


def expr(value):
    return poly(s.Poly(value, *VARS).terms()) if value != 0 else "0"


def row_literal(key):
    depth, k, u, v = key
    return f"⟨{'true' if depth else 'false'}, {k}, {u}, {v}⟩"


def weight(k, i, n, j):
    def falling(e, r):
        return prod(range(e-r+1, e+1))

    return sum((-1)**t * comb(k, t) * falling(i, k-t) * falling(6-i, t)
               * falling(j, t) * falling(max(0, n-j), k-t) for t in range(k+1))


def row_terms(n, key):
    depth, k, u, v = key
    exponents = (1, 3, 4, 5, 6)

    def static(i, deg, j):
        if i+j == u+k and 6-i+max(0, deg-j) == v+k:
            return weight(k, i, deg, j)
        return 0

    terms = []
    for j in range(n+1):
        for i in exponents:
            for h in exponents if depth else (None,):
                scalar = (weight(1, h, n, j)*static(i, n+4, h+j-1)
                          if depth else static(i, n, j))
                if scalar:
                    inner = f"(some {h})" if depth else "none"
                    terms.append(f"⟨{j}, {i}, {inner}, {scalar}⟩")
    return "[" + ", ".join(terms) + "]"


def write(name, lines):
    (HERE / "SexticC3" / f"{name}.lean").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def emit_row(p, i, n, keys, matrix):
    p(f"def row{i} : Row := {row_literal(keys[i])}")
    rhs = " + ".join(f"({expr(x)}) * g {j}" for j, x in enumerate(matrix.row(i)) if x != 0)
    p(f"theorem row{i}_eq (g : Nat → K) :")
    p(f"    rowValue a b c d {n} row{i} g = {rhs} := by")
    p(f"  have ht : rowTerms {n} row{i} = {row_terms(n, keys[i])} := by decide")
    p("  norm_num [rowValue, ht, hCoeff] <;> ring\n")


def emit_degree(record):
    n = record["n"]
    keys, matrix = source.literal_matrix(n)
    if [list(key) for key in keys] != record["row_keys"]:
        raise ValueError("row convention mismatch")
    pivot_rows = record["pivot_rows"]
    minor_rows = record["minor_rows"]
    row_ids = sorted({*pivot_rows, *(r for rows in minor_rows for r in rows)})
    lift = [[source.unpack(p) for p in row] for row in record["kernel_lift"]]
    residual = matrix * s.Matrix(lift)
    lines = [
        "import SexticC3.DeltaData", "",
        "-- Generated by generate.py from the repository's v1 certificate.",
        f"namespace SexticC3.Degree{n}", "",
        "set_option maxHeartbeats 2000000",
        "set_option maxRecDepth 4000",
        "",
        "variable {K : Type*} [Field K] [CharZero K] (a b c d : K)", "",
    ]
    p = lines.append
    for j in range(2):
        p(f"def lift{j} : Nat → K")
        for i, pair in enumerate(record["kernel_lift"]):
            p(f"  | {i} => {poly(pair[j])}")
        p("  | _ => 0\n")

    for i in row_ids:
        emit_row(p, i, n, keys, matrix)

    def lift_ref(j):
        variables = [name for i, name in enumerate("abcd")
                     if any(e[i] for row in record["kernel_lift"] for e, _ in row[j])]
        return f"(lift{j} {' '.join(variables) or '(K := K)'})"

    for i in sorted({r for rows in minor_rows for r in rows}):
        for j in range(2):
            p(f"def res{i}_{j} : K := rowValue a b c d {n} row{i} {lift_ref(j)}")
            p(f"theorem res{i}_{j}_eq : res{i}_{j} a b c d = {expr(s.expand(residual[i,j]))} := by")
            p(f"  rw [res{i}_{j}, row{i}_eq]")
            p(f"  norm_num [lift{j}] <;> ring\n")

    labels = []
    for i, rows in enumerate(minor_rows):
        label = f"gen{i}"
        labels.append(label)
        parts = [f"res{r}_{j}" for r in rows for j in range(2 if n != 6 else 1)]
        args = " ".join(f"({x} a b c d)" for x in parts)
        p(f"def {label} : K := {'minor ' if n != 6 else ''}{args}")
    p("")

    def rhs(terms):
        return " + ".join(f"({poly(coef)}) * ({labels[i]} a b c d)" for i, coef in terms)

    derived = record["derived"]
    for i, node in enumerate(derived):
        label = f"node{i}"
        p(f"def {label} (a b c d : K) : K := {poly(node['polynomial'])}")
        p(f"theorem {label}_eq : {label} a b c d = {rhs(node['terms'])} := by")
        deps = [labels[idx] for idx, _ in node["terms"]]
        gens = [x for x in deps if x.startswith("gen")]
        rows = sorted({r for x in gens for r in minor_rows[int(x[3:])]})
        simp = [label, *deps] + (["minor"] if n != 6 else [])
        simp += [f"res{r}_{j}_eq" for r in rows for j in range(2 if n != 6 else 1)]
        p(f"  simp only [{', '.join(simp)}]")
        p("  ring\n")
        labels.append(label)

    terms = record["discriminant_identity"]
    p(f"theorem recorded_identity : delta a b c d = {rhs(terms)} := by")
    p(f"  unfold delta { ' '.join(labels[idx] for idx, _ in terms) }")
    p("  ring\n")

    # Substitute checked intermediate identities backwards to obtain an explicit
    # representation in the selected minors.
    def flatten(weights):
        out = [s.S.Zero] * len(labels)
        for i, w in weights:
            out[i] += source.unpack(w)
        for j in reversed(range(len(derived))):
            idx = len(minor_rows) + j
            for i, w in derived[j]["terms"]:
                out[i] += s.expand(out[idx] * source.unpack(w))
        return out[:len(minor_rows)]

    p("theorem discriminant_in_selected_span :")
    p("    delta a b c d = " + " + ".join(
        f"({expr(w)}) * ({labels[i]} a b c d)" for i, w in enumerate(flatten(terms)) if w != 0
    ) + " := by")
    p("  rw [recorded_identity]")
    for i in reversed(range(len(derived))):
        p(f"  try rw [node{i}_eq]")
    p("  ring\n")

    p("theorem kernel_bound (g : Nat → K) (h : IsKernel a b c d " + str(n) + " g)")
    p("    (hd : delta a b c d ≠ 0) :")
    if n == 6:
        p("    ∀ j ≤ 6, g j = lift1 a b c d j * g 1 := by")
    elif n == 1:
        p("    g 0 = 0 ∧ g 1 = 0 := by")
    else:
        p(f"    ∀ j ≤ {n}, g j = 0 := by")
    for i in row_ids:
        p(f"  have h{i} := h row{i} (by decide)")
        p(f"  rw [row{i}_eq] at h{i}")
    for j, i in enumerate(pivot_rows, start=2):
        p(f"  have g{j} : g {j} = {lift_ref(0)} {j} * g 0 + {lift_ref(1)} {j} * g 1 := by")
        p("    norm_num [lift0, lift1]")
        if j > 2:
            p(f"    try simp only [{', '.join(f'g{k}' for k in range(2,j))}] at h{i}")
            p(f"    norm_num [lift0, lift1] at h{i}")
        p(f"    linear_combination {scalar(1/matrix[i,j])} * h{i}")
    for i in sorted({r for rows in minor_rows for r in rows}):
        p(f"  have r{i} : res{i}_0 a b c d * g 0 + res{i}_1 a b c d * g 1 = 0 := by")
        p(f"    rw [res{i}_0_eq, res{i}_1_eq]")
        if n > 1:
            p(f"    try simp only [{', '.join(f'g{k}' for k in range(2,n+1))}] at h{i}")
            # Preserve a monomial equality as an equation for linear_combination.
            # Full simp can turn a product equal to zero into a disjunction.
            if sum(len(s.Poly(residual[i, j], *VARS).monoms())
                   for j in range(2) if residual[i, j] != 0) == 1:
                p(f"    try simp only [lift0, lift1] at h{i}")
            else:
                p(f"    norm_num [lift0, lift1] at h{i}")
        p(f"    linear_combination h{i}")
    for i, rows in enumerate(minor_rows):
        if n == 6:
            p(f"  have z{i} : gen{i} a b c d * g 0 = 0 := by")
            p(f"    simpa only [gen{i}, res{rows[0]}_1_eq, zero_mul, add_zero] using r{rows[0]}")
        else:
            p(f"  have z{i} := minor_mul_eq_zero r{rows[0]} r{rows[1]}")
            p(f"  change gen{i} a b c d * g 0 = 0 ∧ gen{i} a b c d * g 1 = 0 at z{i}")

    used = [i for i, w in enumerate(flatten(terms)) if w != 0]
    def finish(j, indent):
        p(f"{indent}apply (mul_eq_zero.mp (show delta a b c d * g {j} = 0 from ?_)).resolve_left hd")
        p(f"{indent}rw [discriminant_in_selected_span]")
        p(f"{indent}simp only [add_mul, mul_assoc, " +
          ", ".join(f"z{i}" + (f".{j+1}" if n != 6 else "") for i in used) + ", mul_zero, add_zero]")
    if n == 6:
        p("  have hz : g 0 = 0 := by")
        finish(0, "    ")
        p("  intro j hj")
        p("  have hj' : j = 0 ∨ j = 1 ∨ j = 2 ∨ j = 3 ∨ j = 4 ∨ j = 5 ∨ j = 6 := by omega")
        p("  rcases hj' with rfl | rfl | rfl | rfl | rfl | rfl | rfl <;>")
        p("    simp [lift0, lift1, hz, g2, g3, g4, g5, g6]")
    elif n == 1:
        p("  constructor")
        for j in range(2):
            p("  ·")
            finish(j, "    ")
    else:
        for j in range(2):
            p(f"  have hz{j} : g {j} = 0 := by")
            finish(j, "    ")
        p("  intro j hj")
        disjunction = " ∨ ".join(f"j = {j}" for j in range(n+1))
        pattern = " | ".join("rfl" for _ in range(n+1))
        reductions = ", ".join(f"g{j}" for j in range(2,n+1))
        p(f"  have hj' : {disjunction} := by omega")
        p(f"  rcases hj' with {pattern} <;> simp [hz0, hz1, {reductions}]")
    if n == 6:
        p("\ntheorem lift1_eq_hCoeff : lift1 a b c d = hCoeff a b c d := by")
        p("  funext j")
        p("  match j with")
        for j in range(7):
            p(f"  | {j} => simp [lift1, hCoeff]")
        p("  | j + 7 => rfl")
        for i in pivot_rows:
            for j in range(2):
                p(f"\ntheorem pivot{i}_{j}_zero : rowValue a b c d 6 row{i} {lift_ref(j)} = 0 := by")
                p(f"  rw [row{i}_eq]")
                p(f"  norm_num [lift{j}] <;> ring")

        core = ["import SexticC3.Degree6", "", "-- Generated by generate.py.",
                "namespace SexticC3.Degree6", "",
                "set_option maxHeartbeats 2000000", "set_option maxRecDepth 4000",
                "", "variable {K : Type*} [Field K] [CharZero K] (a b c d : K)", ""]
        for i in sorted(set(range(len(keys))) - set(row_ids)):
            emit_row(core.append, i, n, keys, matrix)
        core += ["theorem hamiltonian_kernel (t : K) :",
                 "    IsKernel a b c d 6 (fun j => hCoeff a b c d j * t) := by",
                 "  intro r hk",
                 "  by_cases hd : inDegree 6 r",
                 "  · rcases r with ⟨depth, k, u, v⟩",
                 "    change k = 3 ∨ k = 5 at hk",
                 "    cases depth <;> rcases hk with h | h <;> subst k"]
        for depth, k in ((0,3), (0,5), (1,3), (1,5)):
            indices = [i for i, key in enumerate(keys) if key[:2] == (depth, k)]
            disjunction = " ∨ ".join(f"u = {keys[i][2]}" for i in indices)
            pattern = " | ".join("rfl" for _ in indices)
            core.extend(["    · simp [inDegree] at hd",
                         f"      have hu : {disjunction} := by omega",
                         f"      rcases hu with {pattern}"])
            for i in indices:
                core.extend([f"      · have hv : v = {keys[i][3]} := by omega",
                             "        subst v",
                             f"        change rowValue a b c d 6 row{i} _ = 0",
                             f"        rw [row{i}_eq]",
                             "        norm_num [hCoeff] <;> ring"])
        core += ["  · exact rowValue_outside_degree a b c d 6 r _ hd",
                 "", "end SexticC3.Degree6"]
        write("Core6", core)
    p(f"\nend SexticC3.Degree{n}")
    write(f"Degree{n}", lines)


def main():
    raw = (HERE.parent / "squarefree_certificate.json").read_bytes().replace(b"\r\n", b"\n")
    if hashlib.sha256(raw).hexdigest() != EXPECTED:
        raise ValueError("unexpected squarefree certificate SHA-256")
    data = json.loads(raw)
    write("DeltaData", [
        "import SexticC3.Model", "", "-- Generated from the v1 certificate.",
        "namespace SexticC3",
        "def delta {R : Type*} [CommRing R] (a b c d : R) : R :=",
        "  " + poly(data["discriminant"]),
        "end SexticC3",
    ])
    for n in range(1, 17):
        emit_degree(data["records"][n-1])


if __name__ == "__main__":
    main()
